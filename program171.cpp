#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Description   : Prints lowercase alphabets pattern
//  Input         : Integer
//  Output        : None
//  Author        : Varad Nitin Muley
//  Date          : 18/11/2025
//
/////////////////////////////////////////////////////////////////
void Display(int iNo)
{
    int iCnt = 0;
    int i = 96;
 
    for (iCnt = 1 ; iCnt <= iNo ; iCnt++)
    { 
        cout<<(char)(i + iCnt)<<"\t";
    }
    cout<<"\n"; 
}

/////////////////////////////////////////////////////////////////
//
//  Entry point function
//
/////////////////////////////////////////////////////////////////
int main()
{
    int iValue = 0 ;

    cout<<"Enter the Frequency: \n";
    cin>>iValue;

    Display(iValue);

    return 0;
}

