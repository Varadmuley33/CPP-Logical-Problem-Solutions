#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////
//
//  Function name : Display
//  Description   : Attempts to display numbers from -iNo to 0
//  Input         : Integer
//  Output        : Void
//  Author        : Varad Nitin Muley
//  Date          : 18/11/2025
//
/////////////////////////////////////////////////////////////////
void Display(int iNo)
{
    int iCnt = 0 ;

    for(iCnt = -iNo ; iCnt <= 0 ; iCnt++);
    {
        cout<<iCnt<<"\t";
    }

    cout<<"\n";
}

/////////////////////////////////////////////////////////////////
//
//  Entry point function
//
/////////////////////////////////////////////////////////////////
int main()
{
    int iValue = 0 ;

    cout<<"Enter the Frequency : \n";
    cin>>iValue;

    Display(iValue);

    return 0;
}

